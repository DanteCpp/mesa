static inline enum sm5_opcode
sm5_decode_opcode(uint32_t tok)
{
   return (enum sm5_opcode)(tok & 0x7ffu);
}

static inline uint32_t
sm5_decode_inst_len(uint32_t tok)
{
   return (tok >> 24) & 0x7fu;
}

static inline bool
sm5_decode_extended(uint32_t tok)
{
   return (tok >> 31) != 0;
}

static inline bool
sm5_decode_saturate(uint32_t tok)
{
   return (tok & 0x00002000u) != 0;
}

static inline bool
sm5_decode_test_nz(uint32_t tok)
{
   return ((tok >> 18) & 1u) != 0;
}

